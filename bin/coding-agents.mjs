function appendUnderHeading(text, heading, entry) {
  const headingLine = `## ${heading}`;
  const trimmedEntry = entry.trim();
  if (!new RegExp(`^${escapeRegExp(headingLine)}$`, "m").test(text)) {
    return `${text.trimEnd()}\n\n${headingLine}\n\n${trimmedEntry}\n`;
  }

  const headingMatch = new RegExp(`^${escapeRegExp(headingLine)}$`, "m").exec(text);
  const afterHeadingStart = headingMatch.index + headingMatch[0].length;
  const nextHeadingOffset = text.slice(afterHeadingStart).search(/^## /m);
  if (nextHeadingOffset === -1) {
    return `${text.trimEnd()}\n\n${trimmedEntry}\n`;
  }
  const insertAt = afterHeadingStart + nextHeadingOffset;
  const before = text.slice(0, insertAt).trimEnd();
  const after = text.slice(insertAt).trimStart();
  return `${before}\n\n${trimmedEntry}\n\n${after}`;
}

function validateAssignmentFiles(stateDir) {
  const results = [];
  let fatal = false;
  let checkedFiles = 0;
  const assignmentPath = path.join(stateDir, "assignments.md");
  const workflowGate = readWorkflowMetacognitiveContext(stateDir);
  const contractCoverage = readWorkflowContractCoverageContext(stateDir);
  const identity = readWorkflowTaskIdentity(stateDir);

  if (!existsSync(stateDir)) {
    return { results: [["warn", `missing workflow state directory: ${stateDir}`]], fatal: true };
  }

  if (identity.errors.length) {
    results.push(["warn", `invalid workflow identity fields: ${identity.errors.join(", ")}`]);
    fatal = true;
  }
  const taskPath = path.join(stateDir, "task.md");
  if (existsSync(taskPath)) {
    const deliveryValidation = validateDeliveryModeFields(readFileSync(taskPath, "utf8"), {
      allowLegacyDefault: true,
    });
    if (deliveryValidation.valid) {
      results.push([
        "ok",
        deliveryValidation.legacyDefaulted
          ? "legacy task delivery mode defaults non-sticky to ITERATIVE_DELIVERY"
          : `task delivery mode valid (${deliveryValidation.mode})`,
      ]);
    } else {
      results.push(["warn", `invalid task delivery mode: ${deliveryValidation.missing.join(", ")}`]);
      fatal = true;
    }
  }

  if (existsSync(assignmentPath)) {
    checkedFiles += 1;
    const text = readFileSync(assignmentPath, "utf8");
    const roleValidation = validateRoleAssignments(text, workflowGate);
    results.push(...roleValidation.results);
    fatal = fatal || roleValidation.fatal;
    const contractGate = validateContractCoverageGateText(text);
    if (contractGate.valid) results.push(["ok", "contract coverage gate present in assignments"]);
    else {
      results.push(["warn", `contract coverage gate missing from assignments: ${contractGate.missing.join(", ")}`]);
      fatal = true;
    }
  }

  const runnerPath = path.join(stateDir, RUNNER_FILE);
  if (existsSync(runnerPath)) {
    checkedFiles += 1;
    const runnerValidation = validateRunnerPackets(readFileSync(runnerPath, "utf8"), workflowGate, contractCoverage);
    results.push(...runnerValidation.results);
    fatal = fatal || runnerValidation.fatal;
  }

  const todoCompletionValidation = validateTaskTodoCompletionState(stateDir, workflowGate);
  results.push(...todoCompletionValidation.results);
  fatal = fatal || todoCompletionValidation.fatal;

  if (checkedFiles === 0) {
    results.push(["warn", `no assignment files found in ${stateDir}`]);
    fatal = true;
  }

  return { results, fatal };
}

function validateRoleAssignments(text, workflowGate = { required: false }) {
  const results = [];
  let fatal = false;
  const invalidFields = [];

  const roleSections = [...text.matchAll(/^## ([^\n]+)$/gm)]
    .map((match) => match[1].trim())
    .filter((heading) => ![
      "Debugging Integrity Gate",
      CODING_CONDUCT_GATE_NAME,
      METACOGNITIVE_GATE_NAME,
      "Nested Coding Agents Preflight",
      "Subagent Supervision Contract",
    ].includes(heading));

  for (const role of roleSections) {
    const section = getRoleSection(text, role);
    if (!getFieldValue(section, "role")) continue;
    for (const field of ["role", "status", "assignment", "expected_output", "lifecycle"]) {
      if (!getFieldValue(section, field)) invalidFields.push(`${role}.${field}`);
    }
    for (const field of ["task_id", "epoch", "scope"]) {
      for (const error of validateIdentityField(section, field, role)) invalidFields.push(error);
    }
  }

  results.push(["ok", `dynamic role assignment contract present (${roleSections.filter((role) => getFieldValue(getRoleSection(text, role), "role")).length} recorded role section(s))`]);
  if (invalidFields.length === 0) results.push(["ok", "recorded dynamic assignment fields are present and non-empty"]);
  else {
    results.push(["warn", `missing or empty assignment fields: ${invalidFields.join(", ")}`]);
    fatal = true;
  }

  const assignmentSupervision = validateSupervisionContractFields(getSupervisionFieldSection(text));
  if (assignmentSupervision.valid) results.push(["ok", "shared supervision contract present in assignments"]);
  else {
    results.push(["warn", `missing or incomplete supervision assignment fields: ${assignmentSupervision.missing.join(", ")}`]);
    fatal = true;
  }

  const assignmentConduct = validateCodingConductFields(getCodingConductFieldSection(text));
  if (assignmentConduct.valid) {
    results.push(["ok", "shared coding conduct gate present in assignments"]);
  } else {
    const missing = assignmentConduct.missing.map((field) => `assignments.${field}`);
    results.push(["warn", `missing or incomplete coding conduct assignment fields: ${missing.join(", ")}`]);
    fatal = true;
  }

  const assignmentDelivery = validateDeliveryModeFields(text, {
    allowLegacyDefault: workflowGate.deliveryMode?.id !== ONE_SHOT_DELIVERY_MODE,
  });
  if (assignmentDelivery.valid) {
    results.push([
      "ok",
      assignmentDelivery.legacyDefaulted
        ? "legacy assignment delivery mode defaults non-sticky to ITERATIVE_DELIVERY"
        : `shared delivery mode present in assignments (${assignmentDelivery.mode})`,
    ]);
  } else {
    results.push(["warn", `invalid assignment delivery mode: ${assignmentDelivery.missing.join(", ")}`]);
    fatal = true;
  }

  if (text.includes(DEBUG_INTEGRITY)) results.push(["ok", "debugging integrity gate present"]);
  else {
    results.push(["warn", "debugging integrity gate missing from assignments"]);
    fatal = true;
  }

  if (workflowGate.required) {
    const assignmentGate = validateMetacognitiveGateText(text);
    if (assignmentGate.valid) {
      results.push(["ok", "metacognitive gate present in assignments"]);
      results.push(["ok", "shared metacognitive assignment fields are present"]);
    } else {
      results.push(["warn", `metacognitive gate missing from assignments: ${assignmentGate.missing.join(", ")}`]);
      fatal = true;
    }
  }

  return { results, fatal };
}

function validateRunnerPackets(text, workflowGate = { required: false }, contractCoverage = { decisionIds: [], completionIds: [] }) {
  const sections = getModernRunnerPacketSections(text);
  const workerCollectionSections = sections.filter((section) =>
    [WORKER_RESULT_COLLECTION_TYPE, "parent-integration"].includes(getFieldValue(section, "type"))
  );
  const invalidPackets = [];
  const invalidSupervisionPackets = [];
  const invalidCodingConductPackets = [];
  const invalidDeliveryModePackets = [];
  const invalidJobRoutingPackets = [];
  const invalidMetacognitivePackets = [];
  const invalidContractCoveragePackets = [];
  const invalidLifecyclePackets = [];
  const uncollectedCompletedRunnerPackets = [];
  let unknownLegacyLifecyclePackets = 0;
  let checked = 0;

  for (const section of sections) {
    const type = getFieldValue(section, "type");
    if (![
      "assignment",
      WORKER_RESULT_COLLECTION_TYPE,
      "parent-integration",
      TASK_FINALIZATION_TYPE,
      "process-orchestration-skeleton",
      "process-runner-result",
    ].includes(type)) continue;
    checked += 1;
    if (type !== TASK_FINALIZATION_TYPE && !getFieldValue(section, "role")) {
      invalidPackets.push(`${section.split("\n")[0].replace(/^### /, "")}.role`);
    }
    for (const field of ["task_id", "epoch", "scope"]) {
      for (const error of validateIdentityField(section, field, section.split("\n")[0].replace(/^### /, ""))) {
        invalidPackets.push(error);
      }
    }
    const featureProfile = getFieldValue(section, "feature_profile");
    if (featureProfile && !isKnownFeatureProfileId(featureProfile)) {
      invalidPackets.push(`${packetLabel(section)}.feature_profile unknown (${featureProfile})`);
    }
    const workType = getFieldValue(section, "work_type");
    if (workType && !isKnownWorkTypeId(workType)) {
      invalidPackets.push(`${packetLabel(section)}.work_type unknown (${workType})`);
    }
    const currentPacket = isCurrentWorkflowPacket(section, workflowGate);
    const packetDelivery = validateDeliveryModeFields(section, {
      allowLegacyDefault: !currentPacket || workflowGate.deliveryMode?.id !== ONE_SHOT_DELIVERY_MODE,
    });
    if (!packetDelivery.valid) {
      for (const missing of packetDelivery.missing) {
        invalidDeliveryModePackets.push(`${packetLabel(section)}.${missing}`);
      }
    } else if (
      currentPacket
      && packetDelivery.mode !== (workflowGate.deliveryMode?.id || DEFAULT_DELIVERY_MODE)
    ) {
      invalidDeliveryModePackets.push(`${packetLabel(section)}.delivery_mode does not match current task`);
    } else if (
      currentPacket
      && packetDelivery.authority !== (workflowGate.oneShotAuthority || "none")
    ) {
      invalidDeliveryModePackets.push(`${packetLabel(section)}.one_shot_authority does not match current task`);
    }
    if (type === "assignment" || type === "process-orchestration-skeleton") {
      for (const field of ["assignment", "expected_output", "debugging_integrity", "lifecycle"]) {
        if (!getFieldValue(section, field)) {
          invalidPackets.push(`${section.split("\n")[0].replace(/^### /, "")}.${field}`);
        }
      }
      if (!runnerPacketPredatesJobRoutingContract(section, workflowGate)) {
        const routing = validateJobRoutingPacketFields(section);
        for (const missing of routing.missing) {
          invalidJobRoutingPackets.push(`${packetLabel(section)}.${missing}`);
        }
      }
    }
    if ([WORKER_RESULT_COLLECTION_TYPE, "parent-integration"].includes(type)) {
      for (const field of ["status", "debugging_integrity", "lifecycle"]) {
        if (!getFieldValue(section, field)) {
          invalidPackets.push(`${section.split("\n")[0].replace(/^### /, "")}.${field}`);
        }
      }
      const lifecycle = validateIntegrationLifecycleFields(section, workflowGate);
      if (lifecycle.disposition === LEGACY_LIFECYCLE_DISPOSITION) unknownLegacyLifecyclePackets += 1;
      for (const missing of lifecycle.missing) invalidLifecyclePackets.push(`${packetLabel(section)}.${missing}`);
    }
    if (type === TASK_FINALIZATION_TYPE) {
      if (getFieldValue(section, "status") !== "completed") {
        invalidPackets.push(`${packetLabel(section)}.status`);
      }
      const gateValidation = validateContractCoverageGateText(section);
      for (const missing of gateValidation.missing) {
        invalidContractCoveragePackets.push(`${packetLabel(section)}.${missing}`);
      }
      const declaredCoverage = finalizationContractCoverageContext(section);
      if (!declaredCoverage.decisionIds.length) {
        invalidContractCoveragePackets.push(`${packetLabel(section)}.contract_coverage_expected_decision_ids`);
      }
      if (!declaredCoverage.completionIds.length) {
        invalidContractCoveragePackets.push(`${packetLabel(section)}.contract_coverage_expected_completion_ids`);
      }
      for (const mismatch of invalidContractCoverageIdNamespaces(getFieldValue(section, "task_id"), declaredCoverage)) {
        invalidContractCoveragePackets.push(`${packetLabel(section)}.${mismatch}`);
      }
      if (isCurrentWorkflowPacket(section, workflowGate)) {
        for (const missing of missingDeclaredContractCoverageIds(declaredCoverage, contractCoverage)) {
          invalidContractCoveragePackets.push(`${packetLabel(section)}.${missing}`);
        }
      }
      const coverageContext = isCurrentWorkflowPacket(section, workflowGate) ? contractCoverage : declaredCoverage;
      for (const missing of missingContractCoverageFields(section, coverageContext)) {
        invalidContractCoveragePackets.push(`${packetLabel(section)}.${missing}`);
      }
    }
    if (type === "process-runner-result") {
      for (const field of ["status", "runner", "spawned", "exit_code", "summary", "failure", "debugging_integrity", "lifecycle"]) {
        if (!getFieldValue(section, field)) {
          invalidPackets.push(`${section.split("\n")[0].replace(/^### /, "")}.${field}`);
        }
      }
      if (
        isCurrentWorkflowPacket(section, workflowGate)
        && isCompletionStatus(getFieldValue(section, "status"))
        && !hasMatchingWorkerCollection(section, workerCollectionSections)
      ) {
        uncollectedCompletedRunnerPackets.push(`${packetLabel(section)}.${WORKER_RESULT_COLLECTION_TYPE}`);
      }
    }

    if (runnerPacketRequiresSupervision(section)) {
      const supervision = validateSupervisionContractFields(section);
      for (const missing of supervision.missing) invalidSupervisionPackets.push(`${packetLabel(section)}.${missing}`);
    }

    if (type !== TASK_FINALIZATION_TYPE && (!runnerPacketUsesLegacySchema(section) || hasAnyCodingConductField(section))) {
      const conduct = validateCodingConductFields(section);
      for (const missing of conduct.missing) invalidCodingConductPackets.push(`${packetLabel(section)}.${missing}`);
    }

    const packetGate = runnerPacketMetacognitiveRequired(section, workflowGate);
    if (type !== TASK_FINALIZATION_TYPE && packetGate.required) {
      const gateValidation = validateMetacognitiveGateText(section);
      if (!gateValidation.valid) {
        invalidMetacognitivePackets.push(`${packetLabel(section)}.${gateValidation.missing.join("+")}`);
      }

      const status = normalizeStatus(getFieldValue(section, "status"));
      if (isCompletionPacketType(type) && isCompletionStatus(status)) {
        const missing = missingCompletedMetacognitiveFields(readMetacognitiveFieldsFromSection(section));
        for (const field of missing) invalidMetacognitivePackets.push(`${packetLabel(section)}.${field}`);
      }
      if (isCompletionPacketType(type) && isBlockedOrUnresolvedStatus(status)) {
        const missing = missingBlockedMetacognitiveFields(section, type);
        for (const field of missing) invalidMetacognitivePackets.push(`${packetLabel(section)}.${field}`);
      }
    }
  }

  if (
    invalidPackets.length === 0
    && invalidSupervisionPackets.length === 0
    && invalidCodingConductPackets.length === 0
    && invalidDeliveryModePackets.length === 0
    && invalidJobRoutingPackets.length === 0
    && invalidMetacognitivePackets.length === 0
    && invalidContractCoveragePackets.length === 0
    && invalidLifecyclePackets.length === 0
    && uncollectedCompletedRunnerPackets.length === 0
  ) {
    const results = [["ok", `runner packets valid (${checked} checked)`]];
    if (unknownLegacyLifecyclePackets > 0) {
      results.push([
        "ok",
        `legacy parent-integration lifecycle preserved as ${LEGACY_LIFECYCLE_DISPOSITION} (${unknownLegacyLifecyclePackets} checked)`,
      ]);
    }
    return { results, fatal: false };
  }
  const results = [];
  if (invalidPackets.length) results.push(["warn", `missing or empty runner packet fields: ${invalidPackets.join(", ")}`]);
  if (invalidSupervisionPackets.length) {
    results.push(["warn", `missing or incomplete supervision runner packet fields: ${invalidSupervisionPackets.join(", ")}`]);
  }
  if (invalidCodingConductPackets.length) {
    results.push(["warn", `missing or incomplete coding conduct runner packet fields: ${invalidCodingConductPackets.join(", ")}`]);
  }
  if (invalidDeliveryModePackets.length) {
    results.push(["warn", `invalid delivery mode runner packet fields: ${invalidDeliveryModePackets.join(", ")}`]);
  }
  if (invalidJobRoutingPackets.length) {
    results.push(["warn", `missing or invalid model-neutral job routing runner packet fields: ${invalidJobRoutingPackets.join(", ")}`]);
  }
  if (invalidMetacognitivePackets.length) {
    results.push(["warn", `missing or incomplete metacognitive runner packet fields: ${invalidMetacognitivePackets.join(", ")}`]);
  }
  if (invalidContractCoveragePackets.length) {
    results.push([
      "warn",
      `missing or incomplete contract coverage runner packet fields: ${invalidContractCoveragePackets.join(", ")}; accepted typed references: ${CONTRACT_COVERAGE_TYPED_REFERENCE_FORMS}`,
    ]);
  }
  if (invalidLifecyclePackets.length) {
    results.push(["warn", `missing or invalid lifecycle runner packet fields: ${invalidLifecyclePackets.join(", ")}`]);
  }
  if (uncollectedCompletedRunnerPackets.length) {
    results.push([
      "warn",
      `uncollected completed runner result missing follow-up worker result collection: ${uncollectedCompletedRunnerPackets.join(", ")}`,
    ]);
  }
  return { results, fatal: true };
}

function validateIntegrationLifecycleFields(section, workflowGate = {}) {
  const runtimeThreadClosed = getFieldValue(section, "runtime_thread_closed");
  if (runtimeThreadClosed) {
    return {
      valid: false,
      missing: ["runtime_thread_closed unsupported"],
      disposition: getFieldValue(section, "lifecycle_disposition") || LEGACY_LIFECYCLE_DISPOSITION,
    };
  }

  const hasLifecycleFields = INTEGRATION_LIFECYCLE_FIELD_NAMES.some((field) => Boolean(getFieldValue(section, field)));
  if (!hasLifecycleFields) {
    if (isVerifiablyPreContractLifecyclePacket(section, workflowGate)) {
      return { valid: true, missing: [], disposition: LEGACY_LIFECYCLE_DISPOSITION };
    }
    return {
      valid: false,
      missing: [...INTEGRATION_LIFECYCLE_FIELD_NAMES],
      disposition: "missing_current_contract",
    };
  }

  const missing = [];
  if (getFieldValue(section, "lifecycle_contract_version") !== LIFECYCLE_CONTRACT_VERSION) {
    missing.push("lifecycle_contract_version");
  }
  if (getFieldValue(section, "lifecycle_scope") !== LIFECYCLE_SCOPE) missing.push("lifecycle_scope");

  const disposition = getFieldValue(section, "lifecycle_disposition");
  if (!LIFECYCLE_DISPOSITIONS.includes(disposition)) missing.push("lifecycle_disposition");

  const cancelReason = getFieldValue(section, "cancel_reason");
  if (disposition === "state_retired") {
    if (!SUPERVISION_RETIRE_CANCEL_REASONS.includes(cancelReason)) missing.push("cancel_reason");
  } else if (disposition === "continuation_expected") {
    if (cancelReason !== "none") missing.push("cancel_reason");
  } else if (!cancelReason) {
    missing.push("cancel_reason");
  }

  if (getFieldValue(section, "runtime_thread_disposition") !== RUNTIME_THREAD_DISPOSITION) {
    missing.push("runtime_thread_disposition");
  }
  if (getFieldValue(section, "runtime_changed") !== "false") missing.push("runtime_changed");

  return { valid: missing.length === 0, missing, disposition };
}

function isVerifiablyPreContractLifecyclePacket(section, workflowGate) {
  if (!workflowGate?.lifecycleContractVersion) return true;
  if (workflowGate.lifecycleContractVersion !== LIFECYCLE_CONTRACT_VERSION) return false;
  if (isCurrentWorkflowPacket(section, workflowGate)) return false;

  const effectiveAt = Date.parse(workflowGate.lifecycleContractEffectiveAt || "");
  const observedAt = Date.parse(packetTimestamp(section));
  return Number.isFinite(effectiveAt) && Number.isFinite(observedAt) && observedAt < effectiveAt;
}

function isCurrentWorkflowPacket(section, workflowGate) {
  if (!workflowGate?.taskId) return false;
  if (getFieldValue(section, "task_id") !== workflowGate.taskId) return false;
  if (workflowGate.epoch && getFieldValue(section, "epoch") !== workflowGate.epoch) return false;
  if (workflowGate.scope && getFieldValue(section, "scope") !== workflowGate.scope) return false;
  return true;
}

function hasMatchingWorkerCollection(runnerSection, workerCollectionSections) {
  return workerCollectionSections.some((collectionSection) =>
    sameRunnerIdentity(runnerSection, collectionSection)
    && packetTimestamp(collectionSection) >= packetTimestamp(runnerSection)
  );
}

function sameRunnerIdentity(leftSection, rightSection) {
  for (const field of ["role", "task_id", "epoch", "scope"]) {
    if (getFieldValue(leftSection, field) !== getFieldValue(rightSection, field)) return false;
  }
  return featureProfileField(leftSection) === featureProfileField(rightSection)
    && workTypeField(leftSection) === workTypeField(rightSection)
    && deliveryModeField(leftSection) === deliveryModeField(rightSection)
    && oneShotAuthorityField(leftSection) === oneShotAuthorityField(rightSection);
}

function featureProfileField(section) {
  return getFieldValue(section, "feature_profile") || DEFAULT_FEATURE_PROFILE;
}

function workTypeField(section) {
  return getFieldValue(section, "work_type") || DEFAULT_WORK_TYPE;
}

function deliveryModeField(section) {
  return getFieldValue(section, "delivery_mode") || DEFAULT_DELIVERY_MODE;
}

function oneShotAuthorityField(section) {
  return getFieldValue(section, "one_shot_authority") || "none";
}

function packetTimestamp(section) {
  const match = /^###\s+(\S+)/m.exec(section);
  return match ? match[1] : "";
}

function getModernRunnerPacketSections(text) {
  const content = String(text || "");
  const sections = [];
  const starts = [...content.matchAll(/^### /gm)].map((match) => match.index);
  for (let index = 0; index < starts.length; index += 1) {
    const start = starts[index];
    const nextModernStart = starts[index + 1] ?? content.length;
    const legacyOffset = content.slice(start, nextModernStart).search(/^## runner packet:/im);
    const end = legacyOffset === -1 ? nextModernStart : start + legacyOffset;
    sections.push(content.slice(start, end));
  }
  return sections;
}

function classifyMetacognitiveGate(
  parts,
  workType = { id: DEFAULT_WORK_TYPE },
  deliveryMode = { id: DEFAULT_DELIVERY_MODE },
) {
  const workTypeIdValue = typeof workType === "string" ? workType : workType?.id || DEFAULT_WORK_TYPE;
  const deliveryModeIdValue = typeof deliveryMode === "string"
    ? deliveryMode
    : deliveryMode?.id || DEFAULT_DELIVERY_MODE;
  if (workTypeIdValue === "documentation") {
    return { required: false, triggers: [] };
  }
  if (workTypeIdValue === "source-change") {
    return deliveryModeIdValue === ONE_SHOT_DELIVERY_MODE
      ? { required: true, triggers: ["ONE_SHOT_QUALITY source-change"] }
      : { required: false, triggers: [] };
  }
  if (workTypeIdValue === "debug") {
    return { required: true, triggers: ["work_type: debug"] };
  }
  const text = Object.values(parts || {})
    .filter((value) => value !== undefined && value !== null)
    .map((value) => String(value))
    .join("\n");
  const triggers = [];
  for (const [label, pattern] of METACOGNITIVE_TRIGGER_PATTERNS) {
    if (pattern.test(text) && (deliveryModeIdValue === ONE_SHOT_DELIVERY_MODE || label !== "source change")) {
      triggers.push(label);
    }
  }
  if (
    deliveryModeIdValue === ONE_SHOT_DELIVERY_MODE
    && hasSourceTestConfigPathScope(parts?.scope)
  ) {
    triggers.push("ONE_SHOT_QUALITY source/test/config path scope");
  }
  return {
    required: triggers.length > 0,
    triggers: [...new Set(triggers)],
  };
}

function hasSourceTestConfigPathScope(scope) {
  const text = String(scope || "");
  return /(?:^|[\s,;])(?:\.?\/)?(?:bin|src|lib|app|apps|packages|server|client|components|pages|routes|tests?|__tests__|spec|scripts|config|configs|\.github\/workflows)\/[^\s,;]+/i.test(text)
    || /(?:^|[\s,;])(?:package(?:-lock)?\.json|pnpm-lock\.yaml|yarn\.lock|tsconfig(?:\.[^/\s,;]+)?\.json|jsconfig\.json|vite\.config\.[cm]?[jt]s|next\.config\.[cm]?[jt]s|jest\.config\.[cm]?[jt]s|vitest\.config\.[cm]?[jt]s|eslint\.config\.[cm]?[jt]s|\.eslintrc(?:\.[a-z]+)?|\.prettierrc(?:\.[a-z]+)?|Cargo\.toml|Cargo\.lock|go\.mod|go\.sum|pyproject\.toml|requirements(?:-[^/\s,;]+)?\.txt|uv\.lock|deno\.json|wrangler\.toml)(?=$|[\s,;])/i.test(text)
    || /(?:^|[\s,;])(?:[A-Za-z0-9_.-]+\/)+[A-Za-z0-9_.-]+\.(?:mjs|cjs|js|jsx|ts|tsx|py|rs|go|rb|java|kt|swift|sh|bash|zsh|json|ya?ml|toml)(?=$|[\s,;])/i.test(text);
}

function mergeMetacognitiveGates(...gates) {
  const triggers = [];
  for (const gate of gates) {
    if (!gate) continue;
    if (gate.required) triggers.push(...(gate.triggers || []));
  }
  return {
    required: triggers.length > 0,
    triggers: [...new Set(triggers)],
  };
}

function readWorkflowMetacognitiveContext(stateDir) {
  const taskPath = path.join(stateDir, "task.md");
  if (!existsSync(taskPath)) return { required: false, triggers: [], taskId: null };
  const text = readFileSync(taskPath, "utf8");
  const identity = readWorkflowTaskIdentity(stateDir);
  const taskId = identity.taskId;
  const epoch = identity.epoch;
  const scope = identity.scope;
  const task = getFieldValue(text, "task");
  const workType = resolveWorkType(getFieldValue(text, "work_type") || DEFAULT_WORK_TYPE);
  const deliveryContext = readWorkflowDeliveryContext(stateDir);
  const lifecycleContractVersion = getFieldValue(text, "lifecycle_contract_version");
  const lifecycleContractEffectiveAt = getFieldValue(text, "lifecycle_contract_effective_at");
  const jobRoutingContractVersion = getFieldValue(text, "job_routing_contract_version");
  const jobRoutingContractEffectiveAt = getFieldValue(text, "job_routing_contract_effective_at");
  const gateSection = getMetacognitiveGateFieldSection(text);
  const declaredRequired = getFieldValue(gateSection, "metacognitive_gate_required") === "true";
  const declaredTriggers = splitList(getFieldValue(gateSection, "metacognitive_gate_triggers")).filter((item) => item !== "none");
  const classified = classifyMetacognitiveGate(
    { task, scope },
    workType,
    deliveryContext.deliveryMode,
  );
  const gate = mergeMetacognitiveGates(
    classified,
    declaredRequired ? { required: true, triggers: declaredTriggers.length ? declaredTriggers : ["declared"] } : null,
  );
  return {
    ...gate,
    taskId,
    epoch,
    scope,
    task,
    workType,
    deliveryMode: deliveryContext.deliveryMode,
    oneShotAuthority: deliveryContext.oneShotAuthority,
    lifecycleContractVersion,
    lifecycleContractEffectiveAt,
    jobRoutingContractVersion,
    jobRoutingContractEffectiveAt,
    identityErrors: identity.errors,
  };
}

