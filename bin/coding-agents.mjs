function assertNamedStateDirGitSafe(gitRoot, stateDirName) {
  const tracked = readGitOutput(gitRoot, ["ls-files", "--", stateDirName], "check tracked workflow state").trim();
  if (tracked) {
    throw new CliError(`refusing to write state: ${stateDirName} is tracked by Git:\n${tracked}`, 1);
  }

  const status = readGitOutput(gitRoot, ["status", "--short", "--", stateDirName], "check workflow state status").trim();
  if (status) {
    throw new CliError(
      `refusing to write state: ${stateDirName} appears in git status after adding ${stateDirName}/ to git info exclude:\n${status}`,
      1,
    );
  }
}

function readGitOutput(gitRoot, args, label) {
  try {
    return execFileSync("git", ["-C", gitRoot, ...args], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (error) {
    const detail = String(error.stderr || error.message).trim();
    throw new CliError(`${label} failed: ${detail}`, 1);
  }
}

