function main() {
  const args = parseArgs(process.argv.slice(2));
  for (const field of ["model", "modelName", "workerModel", "reasoning", "reasoningEffort"]) {
    if (args[field] !== undefined) {
      fail("model and reasoning-effort selection are owned by root Sol at official spawn time and cannot be recorded by this CLI", 1);
    }
  }
  if (args.runtimeThreadClosed !== undefined) {
    fail("--runtime-thread-closed is unsupported by every command: the workflow CLI cannot close or reclaim runtime threads", 1);
  }
  if (args.runner !== undefined || args.timeoutMs !== undefined) {
    fail("--runner and --timeout-ms are unsupported: this CLI never launches Codex workers; use the official Codex subagent spawn tools", 1);
  }
  if (args.help || !args.command) {
    printHelp();
    process.exit(0);
  }

  try {
    if (args.command === "intake") intake(args);
    else if (args.command === "handoff") handoff(args);
    else if (args.command === "doctor") doctor(args);
    else if (args.command === "verify-assignments") verifyAssignments(args);
    else if (args.command === "normalize-debugging-integrity") normalizeDebuggingIntegrity(args);
    else if (args.command === "assign") assign(args);
    else if (args.command === "collect") collect(args);
    else if (args.command === "finalize") finalize(args);
    else if (args.command === "run" || args.command === "orchestrate") run(args);
    else fail(`unknown command: ${args.command}`, 1);
  } catch (error) {
    fail(error.message, error.exitCode ?? 1);
  }
}

function parseArgs(argv) {
  const parsed = { command: null, help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === "--help" || token === "-h") {
      parsed.help = true;
      continue;
    }
    if (!parsed.command && !token.startsWith("--")) {
      parsed.command = token;
      continue;
    }
    if (token.startsWith("--")) {
      const key = token.slice(2);
      if (["execute", "dry-run"].includes(key)) {
        parsed[toCamel(key)] = true;
        continue;
      }
      const value = argv[i + 1];
      if (!value || value.startsWith("--")) {
        throw new CliError(`missing value for --${key}`);
      }
      const parsedKey = toCamel(key);
      if (["lifecycle-disposition", "cancel-reason"].includes(key) && Object.hasOwn(parsed, parsedKey)) {
        throw new CliError(`duplicate --${key}; provide exactly one value`);
      }
      parsed[parsedKey] = value;
      i += 1;
      continue;
    }
    throw new CliError(`unexpected argument: ${token}`);
  }
  return parsed;
}

function intake(args) {
  const commandContext = resolveCommandContext(args);
  const task = requireArg(args.task, "--task");
  const taskId = requireIdentityArg(args.taskId, "--task-id");
  const epoch = requireIdentityArg(args.epoch, "--epoch");
  const scope = requireIdentityArg(args.scope, "--scope");
  const evidenceRef = args.evidenceRef ?? "none";
  if (
    args.evidenceRef !== undefined &&
    !hasTypedContractCoverageReference(args.evidenceRef)
  ) {
    throw new CliError(
      `--evidence-ref must contain a concrete typed reference (${CONTRACT_COVERAGE_TYPED_REFERENCE_FORMS})`,
    );
  }
  const metacognitiveGate = classifyMetacognitiveGate(
    { task, scope },
    commandContext.workType,
    commandContext.deliveryMode,
  );
  const state = resolveWorkflowState(commandContext.targetCwd);
  prepareStateWrite(state);
  mkdirSync(state.stateDir, { recursive: true });

  const context = {
    cwd: commandContext.targetCwd,
    invocationCwd: commandContext.invocationCwd,
    targetCwd: commandContext.targetCwd,
    task,
    taskId,
    epoch,
    scope,
    evidenceRef,
    workType: commandContext.workType,
    deliveryMode: commandContext.deliveryMode,
    oneShotAuthority: commandContext.oneShotAuthority,
    stateDir: state.stateDir,
    gitRoot: state.gitRoot,
    timestamp: new Date().toISOString(),
    gitStatus: readGitStatus(commandContext.targetCwd),
    metacognitiveGate,
  };

  for (const [file, body] of Object.entries(renderDocs(context))) {
    upsertGenerated(path.join(state.stateDir, file), body);
  }

  console.log(`ok intake: updated ${state.stateDir}`);
  console.log(`ok task_id: ${taskId}`);
  console.log(`ok epoch: ${epoch}`);
  console.log(`ok scope: ${scope}`);
  console.log(`ok evidence_ref: ${evidenceRef}`);
  console.log(`ok work_type: ${workTypeId(commandContext)}`);
  console.log(`ok delivery_mode: ${deliveryModeId(commandContext)}`);
  console.log(`ok one_shot_authority: ${commandContext.oneShotAuthority}`);
  console.log(`ok metacognitive_gate_required: ${metacognitiveGate.required}`);
  if (metacognitiveGate.required) console.log(`ok metacognitive_gate_triggers: ${metacognitiveGate.triggers.join(", ")}`);
  printLegacyHints(state);
}

